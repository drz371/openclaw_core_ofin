╚══════════════════════════════════════════════════════════════════════╝

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

📝 问题描述

  求函数 f(x) = x³ - 6x² + 11x - 6 的零点

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

🔢 求解过程

  方法: 因式分解法

  观察发现:
  f(x) = x³ - 6x² + 11x - 6
       = (x-1)(x²-5x+6)     [提取 x=1 的因子]
       = (x-1)(x-2)(x-3)    [继续分解]

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

✅ 最终答案

  函数的三个零点为:

    ╔═══════════════════════════════════════════════════════════════╗
    ║                                                               ║
    ║     x₁ = 1        x₂ = 2        x₃ = 3                     ║
    ║                                                               ║
    ╚═══════════════════════════════════════════════════════════════╝

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

🔍 验证

  f(1) = 1³ - 6(1)² + 11(1) - 6 = 1 - 6 + 11 - 6 = 0  ✅
  f(2) = 2³ - 6(2)² + 11(2) - 6 = 8 - 24 + 22 - 6 = 0  ✅
  f(3) = 3³ - 6(3)² + 11(3) - 6 = 27 - 54 + 33 - 6 = 0  ✅

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

📐 扩展知识

  • 导数: f'(x) = 3x² - 12x + 11
  • 导数零点: x = 2 ± √3/3 ≈ 1.42, 2.58
  • 极值点: (1.42, -0.38) 极小值, (2.58, 0.38) 极大值
  • 该三次函数图像与x轴有三个交点

